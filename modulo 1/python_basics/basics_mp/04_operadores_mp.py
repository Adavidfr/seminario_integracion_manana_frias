#Operadores para cálculos de nómina
salario_base = 1500
bono_desempeño = 200
print("Suma")
print(salario_base,"+", bono_desempeño, "=", salario_base + bono_desempeño)
print("Resta")
print(salario_base,"-", bono_desempeño, "=", salario_base - bono_desempeño)
print("Multiplicación")
print(salario_base,"*", bono_desempeño, "=", salario_base * bono_desempeño)
print("División")
print(salario_base,"/", bono_desempeño, "=", salario_base / bono_desempeño)
print("Modulo")
print(salario_base,"%", bono_desempeño, "=", salario_base % bono_desempeño)
print("Operador de Asignación")
print("="*25)
